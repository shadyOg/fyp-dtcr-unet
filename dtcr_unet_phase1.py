# ---------- MosMedData helpers ----------
def find_ct_path(study_id):
    for ct_folder in ['CT-0', 'CT-1', 'CT-2', 'CT-3', 'CT-4']:
        candidate = studies_root / ct_folder / f"{study_id}.nii"
        if candidate.exists():
            return candidate
    return None

def normalize_ct_slice(slice_2d, hu_min=-1000, hu_max=400):
    """Clip to a lung-relevant HU window, then scale to [0,1]."""
    clipped = np.clip(slice_2d, hu_min, hu_max)
    normalized = (clipped - hu_min) / (hu_max - hu_min)
    return normalized.astype(np.float32)

def resize_if_needed(img, is_mask):
    if img.shape[0] != TARGET_SIZE or img.shape[1] != TARGET_SIZE:
        interp = cv2.INTER_NEAREST if is_mask else cv2.INTER_LINEAR
        img = cv2.resize(img, (TARGET_SIZE, TARGET_SIZE), interpolation=interp)
    return img

# ---------- LIDC-IDRI helpers ----------
def load_lidc_image(path):
    img = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
    if img is None:
        return None
    if img.ndim == 3:
        img = cv2.cvtColor(img[:, :, :3], cv2.COLOR_BGR2GRAY)
    return img

def load_lidc_mask(path):
    m = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
    if m is None:
        return None
    if m.ndim == 3:
        m = cv2.cvtColor(m[:, :, :3], cv2.COLOR_BGR2GRAY)
    return m

def resize_lidc(arr, is_mask):
    interp = cv2.INTER_NEAREST if is_mask else cv2.INTER_LINEAR
    return cv2.resize(arr, (TARGET_SIZE, TARGET_SIZE), interpolation=interp)

