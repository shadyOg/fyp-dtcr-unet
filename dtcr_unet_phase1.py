"""## Cell 8 - LIDC-IDRI: collect pairs, subsample to ~1000, patient-level split

Subsampled at the **patient** level to roughly match MosMedData's volume (LIDC-IDRI has ~9700
pairs across 578 patients if used in full — far more than MosMedData, which would badly skew
the hybrid set toward LIDC-IDRI's nodule-crop visual style).

"""

lidc_triples = []
