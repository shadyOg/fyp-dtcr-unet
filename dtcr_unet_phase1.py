pairs_by_patient = {}
for img_path, mask_path, patient in lidc_triples:
    pairs_by_patient.setdefault(patient, []).append((img_path, mask_path))

# Sort each patient's own pair list too -- without this, a patient's slices
# could still land in a different internal order between runs, which would
# change which pair gets index 0, 1, 2... in the saved filenames.
for patient in pairs_by_patient:
    pairs_by_patient[patient].sort(key=lambda pair: str(pair[0]))

